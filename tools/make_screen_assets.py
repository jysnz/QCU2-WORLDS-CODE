"""Bakes the brain-screen assets into src/screen_assets.cpp (see include/screen_assets.hpp).

    python tools/make_screen_assets.py

- Logo: tools/qcu_logo.png, cropped and baked at two sizes -- LOGO for the boot splash
  and LOGO_SMALL for the dashboard header -- each quantized to a 256-color palette
  (1 byte/pixel) to keep the upload small. Transparent pixels get palette alpha 0 so
  the background shows through.
- Fonts: tools/fonts/RobotoCondensed-Bold.ttf (Apache 2.0) rendered to 8-bit
  anti-aliased glyph bitmaps for ASCII 32-126 plus the degree sign.

Needs Pillow:  pip install pillow
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

TOOLS = Path(__file__).resolve().parent
OUT = TOOLS.parent / "src" / "screen_assets.cpp"
LOGOS = {"LOGO": 200, "LOGO_SMALL": 34}  # name -> height in pixels
FONT_FILE = TOOLS / "fonts" / "RobotoCondensed-Bold.ttf"
FONTS = {"FONT_SMALL": 13, "FONT_MEDIUM": 16, "FONT_LARGE": 22, "FONT_XLARGE": 30}
CHARS = [chr(c) for c in range(32, 127)] + ["°"]  # index 95 = degree sign


def c_bytes(f, data, per_line=32):
    for i in range(0, len(data), per_line):
        f.write("    " + ",".join(str(b) for b in data[i : i + per_line]) + ",\n")


def write_logo(f, name, height):
    im = Image.open(TOOLS / "qcu_logo.png").convert("RGBA")
    im = im.crop(im.getchannel("A").getbbox())
    width = round(im.width * height / im.height)
    im = im.resize((width, height), Image.LANCZOS)

    # Quantize color and alpha together (RGBA palette) so soft edges stay soft.
    q = im.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    pal = q.getpalette(rawmode="RGBA")[: 256 * 4]
    pal += [0] * (256 * 4 - len(pal))
    colors = [(pal[i + 3] << 24) | (pal[i] << 16) | (pal[i + 1] << 8) | pal[i + 2] for i in range(0, 256 * 4, 4)]

    lname = name.lower()
    f.write("// 0xAARRGGBB\n")
    f.write(f"static const std::uint32_t {lname}_palette[256] = {{\n")
    for i in range(0, 256, 8):
        f.write("    " + ", ".join(f"0x{c:08X}" for c in colors[i : i + 8]) + ",\n")
    f.write("};\n\n")
    f.write(f"static const std::uint8_t {lname}_pixels[{width * height}] = {{\n")
    c_bytes(f, q.tobytes(), 24)
    f.write("};\n\n")
    f.write(f"const Image {name} = {{{width}, {height}, {lname}_palette, {lname}_pixels}};\n\n")
    return width


def write_font(f, name, size):
    font = ImageFont.truetype(str(FONT_FILE), size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in CHARS:
        advance = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="la")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="la")
            data = img.tobytes()
        else:
            data = b""
        glyphs.append((len(bitmap), w, h, x0, y0, advance))
        bitmap += data

    lname = name.lower()
    f.write(f"static const std::uint8_t {lname}_bitmap[{max(1, len(bitmap))}] = {{\n")
    c_bytes(f, bitmap or b"\0")
    f.write("};\n\n")
    f.write(f"static const Glyph {lname}_glyphs[{len(glyphs)}] = {{\n")
    for off, w, h, x0, y0, adv in glyphs:
        f.write(f"    {{{off}, {w}, {h}, {x0}, {y0}, {adv}}},\n")
    f.write("};\n\n")
    f.write(f"const Font {name} = {{{lname}_glyphs, {lname}_bitmap, {ascent}, {ascent + descent}}};\n\n")


with open(OUT, "w", newline="\n") as f:
    f.write("// Generated by tools/make_screen_assets.py -- do not edit by hand.\n")
    f.write('#include "screen_assets.hpp"\n\n')
    logos = [f"{name}={write_logo(f, name, h)}x{h}" for name, h in LOGOS.items()]
    for name, size in FONTS.items():
        write_font(f, name, size)

print(f"wrote {OUT} ({', '.join(logos)}, fonts {', '.join(f'{n}={s}px' for n, s in FONTS.items())})")
